# 添加 tree 节点 (递归查找父节点,不限于顶层)
def add_node(tree, path, new_node):
    if not path:
        # 避免重复
        if not any(n.get('name') == new_node.get('name') for n in tree):
            tree.append(new_node)
        return True
    head = path[0]
    for n in tree:
        if n['name'] == head:
            if not n.get('children'):
                n['children'] = []
            return add_node(n['children'], path[1:], new_node)
    # 递归查找深层
    for n in tree:
        if n.get('children'):
            if add_node(n['children'], path, new_node):
                return True
    return False

